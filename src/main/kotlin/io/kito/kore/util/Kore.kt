package io.kito.kore.util

/**
 * Type alias for representing game ticks.
 * A tick is a unit of time in Minecraft, typically 20 ticks per second.
 */
typealias Ticks = Int

/**
 * Type alias for representing a quantity in grams.
 * Used for measurements where mass is relevant.
 */
typealias Grams  = Double
/**
 * Type alias for representing a quantity in milibuckets.
 * Used for fluid measurements, where 1000 milibuckets equals 1 bucket.
 */
typealias Milibuckets = Double

